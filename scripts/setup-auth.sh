#!/usr/bin/env bash
# Create MQTT users + ACL for mosquitto and the browser config.
#   ./scripts/setup-auth.sh             create .env (random passwords) if missing, write secrets
#   ./scripts/setup-auth.sh --rotate    generate new passwords
#   ./scripts/setup-auth.sh --acl-only  only re-apply mosquitto/acl
# Secrets live in .env and mosquitto/secrets/ (both git-ignored).
set -euo pipefail
cd "$(dirname "$0")/.."

USERS=(simulator sysmon alarmd dashboard)
IMAGE=eclipse-mosquitto:2

gen() { python3 -c 'import secrets; print(secrets.token_urlsafe(18))'; }

if [[ "${1:-}" == "--rotate" ]]; then rm -f .env; fi

if [[ "${1:-}" != "--acl-only" ]]; then
  if [[ ! -f .env ]]; then
    {
      echo "# MQTT credentials (generated by scripts/setup-auth.sh, do not commit)"
      for u in "${USERS[@]}"; do echo "MQTT_PASS_${u^^}=$(gen)"; done
    } > .env
    chmod 600 .env
    echo "created .env"
  fi
  set -a; . ./.env; set +a

  # browser dashboard connects with the (read-mostly) dashboard account
  cat > dashboard/config.js <<EOF
// generated by scripts/setup-auth.sh, do not commit
window.MQTT_CONFIG = { username: "dashboard", password: "${MQTT_PASS_DASHBOARD}" };
EOF
fi

set -a; . ./.env; set +a
mkdir -p mosquitto/secrets mosquitto/data
# build passwd + acl inside the mosquitto image so the files end up owned by the
# broker's uid with 0600 permissions (mosquitto refuses world-readable secrets)
docker run --rm --user root \
  -e U1=simulator -e P1="$MQTT_PASS_SIMULATOR" \
  -e U2=sysmon    -e P2="$MQTT_PASS_SYSMON" \
  -e U3=alarmd    -e P3="$MQTT_PASS_ALARMD" \
  -e U4=dashboard -e P4="$MQTT_PASS_DASHBOARD" \
  -e ACL_ONLY="${1:-}" \
  -v "$PWD/mosquitto:/m" "$IMAGE" sh -c '
    set -e
    umask 077
    if [ "$ACL_ONLY" != "--acl-only" ]; then
      rm -f /m/secrets/passwd; touch /m/secrets/passwd
      for i in 1 2 3 4; do
        eval "mosquitto_passwd -b /m/secrets/passwd \"\$U$i\" \"\$P$i\""
      done
    fi
    cp /m/acl /m/secrets/acl
    chown -R 1883:1883 /m/secrets /m/data
    chmod 700 /m/secrets; chmod 600 /m/secrets/*'
# secrets/ is only readable by the broker's uid; this marker tells run.sh setup is done
touch mosquitto/.auth-ready

if docker compose ps --status running --services 2>/dev/null | grep -qx mosquitto; then
  docker compose kill -s HUP mosquitto > /dev/null   # reload passwd + acl without restart
  echo "mosquitto reloaded"
fi
echo "auth ready for: ${USERS[*]}"
